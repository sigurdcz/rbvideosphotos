CREATE TABLE IF NOT EXISTS `gtm_connections` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `site_id` INT UNSIGNED NOT NULL,
  `status` ENUM('disconnected','connected','error') NOT NULL DEFAULT 'disconnected',
  `google_account_email` VARCHAR(255) DEFAULT NULL,
  `google_account_name` VARCHAR(255) DEFAULT NULL,
  `access_token_encrypted` LONGTEXT DEFAULT NULL,
  `refresh_token_encrypted` LONGTEXT DEFAULT NULL,
  `token_scopes` TEXT DEFAULT NULL,
  `token_expires_at` DATETIME DEFAULT NULL,
  `account_id` VARCHAR(64) DEFAULT NULL,
  `account_name` VARCHAR(255) DEFAULT NULL,
  `container_id` VARCHAR(64) DEFAULT NULL,
  `container_name` VARCHAR(255) DEFAULT NULL,
  `workspace_id` VARCHAR(64) DEFAULT NULL,
  `workspace_name` VARCHAR(255) DEFAULT NULL,
  `workspace_path` VARCHAR(255) DEFAULT NULL,
  `workspace_fingerprint` VARCHAR(255) DEFAULT NULL,
  `last_inventory_at` DATETIME DEFAULT NULL,
  `last_synced_at` DATETIME DEFAULT NULL,
  `last_verified_at` DATETIME DEFAULT NULL,
  `last_error` TEXT DEFAULT NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_gtm_connections_site` (`site_id`),
  KEY `idx_gtm_connections_status` (`status`),
  CONSTRAINT `fk_gtm_connections_site` FOREIGN KEY (`site_id`) REFERENCES `sites` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `gtm_event_definitions` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `site_id` INT UNSIGNED NOT NULL,
  `event_key` VARCHAR(120) NOT NULL,
  `label` VARCHAR(255) NOT NULL,
  `description` TEXT DEFAULT NULL,
  `category` VARCHAR(120) NOT NULL,
  `enabled` TINYINT(1) NOT NULL DEFAULT 1,
  `trigger_type` VARCHAR(64) NOT NULL DEFAULT 'custom_event',
  `tag_type` VARCHAR(64) NOT NULL DEFAULT 'gaawe',
  `tag_name` VARCHAR(255) NOT NULL,
  `trigger_name` VARCHAR(255) NOT NULL,
  `tag_parameter_json` LONGTEXT DEFAULT NULL,
  `trigger_filter_json` LONGTEXT DEFAULT NULL,
  `notes_json` LONGTEXT DEFAULT NULL,
  `local_version` INT UNSIGNED NOT NULL DEFAULT 1,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_gtm_events_site_key` (`site_id`, `event_key`),
  KEY `idx_gtm_events_site_enabled` (`site_id`, `enabled`),
  CONSTRAINT `fk_gtm_events_site` FOREIGN KEY (`site_id`) REFERENCES `sites` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `gtm_managed_entities` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `site_id` INT UNSIGNED NOT NULL,
  `event_definition_id` INT UNSIGNED DEFAULT NULL,
  `entity_type` ENUM('tag','trigger','variable','folder') NOT NULL,
  `management_key` VARCHAR(255) NOT NULL,
  `display_name` VARCHAR(255) NOT NULL,
  `ownership` ENUM('managed','adopted','external') NOT NULL DEFAULT 'managed',
  `remote_path` VARCHAR(255) DEFAULT NULL,
  `remote_id` VARCHAR(64) DEFAULT NULL,
  `fingerprint` VARCHAR(255) DEFAULT NULL,
  `config_hash` CHAR(64) NOT NULL,
  `payload_json` LONGTEXT DEFAULT NULL,
  `last_status` ENUM('new','update','noop','conflict','duplicate','deleted') NOT NULL DEFAULT 'new',
  `last_error` TEXT DEFAULT NULL,
  `last_seen_at` DATETIME DEFAULT NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_gtm_entities_site_key` (`site_id`, `management_key`),
  KEY `idx_gtm_entities_site_type` (`site_id`, `entity_type`),
  CONSTRAINT `fk_gtm_entities_site` FOREIGN KEY (`site_id`) REFERENCES `sites` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_gtm_entities_event` FOREIGN KEY (`event_definition_id`) REFERENCES `gtm_event_definitions` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `gtm_sync_runs` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `site_id` INT UNSIGNED NOT NULL,
  `connection_id` INT UNSIGNED DEFAULT NULL,
  `user_id` INT UNSIGNED DEFAULT NULL,
  `run_type` ENUM('inventory','plan','apply','version','publish') NOT NULL,
  `status` ENUM('pending','running','succeeded','failed','conflict') NOT NULL DEFAULT 'pending',
  `summary` VARCHAR(500) DEFAULT NULL,
  `request_id` VARCHAR(120) DEFAULT NULL,
  `sync_status_json` LONGTEXT DEFAULT NULL,
  `merge_conflicts_json` LONGTEXT DEFAULT NULL,
  `error_code` VARCHAR(100) DEFAULT NULL,
  `error_message` TEXT DEFAULT NULL,
  `started_at` DATETIME DEFAULT NULL,
  `finished_at` DATETIME DEFAULT NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_gtm_sync_runs_site_status` (`site_id`, `status`),
  KEY `idx_gtm_sync_runs_connection` (`connection_id`),
  CONSTRAINT `fk_gtm_sync_runs_site` FOREIGN KEY (`site_id`) REFERENCES `sites` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_gtm_sync_runs_connection` FOREIGN KEY (`connection_id`) REFERENCES `gtm_connections` (`id`) ON DELETE SET NULL,
  CONSTRAINT `fk_gtm_sync_runs_user` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `gtm_sync_operations` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `sync_run_id` INT UNSIGNED NOT NULL,
  `operation_order` INT UNSIGNED NOT NULL DEFAULT 0,
  `entity_type` ENUM('tag','trigger','variable','folder') NOT NULL,
  `action` ENUM('create','update','noop','conflict','delete') NOT NULL,
