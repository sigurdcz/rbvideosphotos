  `remote_path` VARCHAR(255) DEFAULT NULL,
  `status` ENUM('pending','running','succeeded','failed','conflict') NOT NULL DEFAULT 'pending',
  `summary` VARCHAR(500) DEFAULT NULL,
  `request_json` LONGTEXT DEFAULT NULL,
  `response_json` LONGTEXT DEFAULT NULL,
  `error_message` TEXT DEFAULT NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_gtm_sync_ops_run` (`sync_run_id`, `operation_order`),
  CONSTRAINT `fk_gtm_sync_ops_run` FOREIGN KEY (`sync_run_id`) REFERENCES `gtm_sync_runs` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `gtm_container_versions` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `site_id` INT UNSIGNED NOT NULL,
  `connection_id` INT UNSIGNED DEFAULT NULL,
  `sync_run_id` INT UNSIGNED DEFAULT NULL,
  `container_version_id` VARCHAR(64) NOT NULL,
  `version_name` VARCHAR(255) NOT NULL,
  `version_path` VARCHAR(255) DEFAULT NULL,
  `fingerprint` VARCHAR(255) DEFAULT NULL,
  `published` TINYINT(1) NOT NULL DEFAULT 0,
  `compiler_error` TINYINT(1) DEFAULT NULL,
  `new_workspace_path` VARCHAR(255) DEFAULT NULL,
  `note` TEXT DEFAULT NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_gtm_versions_site_version` (`site_id`, `container_version_id`),
  KEY `idx_gtm_versions_connection` (`connection_id`),
  KEY `idx_gtm_versions_run` (`sync_run_id`),
  CONSTRAINT `fk_gtm_versions_site` FOREIGN KEY (`site_id`) REFERENCES `sites` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_gtm_versions_connection` FOREIGN KEY (`connection_id`) REFERENCES `gtm_connections` (`id`) ON DELETE SET NULL,
  CONSTRAINT `fk_gtm_versions_run` FOREIGN KEY (`sync_run_id`) REFERENCES `gtm_sync_runs` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
